// Finds which planned art and sound files exist in the library's assets/ folder and writes src/asset-files.js.
// Run after adding or renaming art:   node tools/scan-assets.mjs
// Art: the newest version of each planned file wins (sammy-run-strip-v02.png over -v01.png).
// Every PNG found is checked for size, colour-profile data, semi-transparent pixels and off-palette colours.
// Options: --root <library folder> (default: the folder above game/)   --out <file>
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { checkPng } from './png.mjs';

const gameDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadLists() {
  const ctx = { globalThis: {} };
  ctx.globalThis = ctx;
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(gameDir, 'src', 'assets.js'), 'utf8'), ctx);
  return ctx.SAMMY;
}
export function loadManifest() { return loadLists().ASSET_MANIFEST; }

// For each planned sound: the newest version of each variation, in every format present.
// A .wav is skipped when the same sound also exists as .ogg or .mp3 (the .wav is then the master copy).
function scanSounds(assetsDir, S) {
  const sounds = {}, masters = [], older = [];
  for (const m of S.SOUND_MANIFEST) {
    const dir = path.join(assetsDir, m.dir);
    if (!fs.existsSync(dir)) continue;
    const variants = {}, all = [];
    for (const name of fs.readdirSync(dir)) {
      const info = S.soundFileInfo(m.id, name);
      if (!info) continue;
      all.push(m.dir + name);
      const v = variants[info.variant] = variants[info.variant] || { version: -1, files: [] };
      if (info.version > v.version) { v.version = info.version; v.files = []; }
      if (info.version === v.version) v.files.push({ name, format: info.format });
    }
    const files = [];
    for (const key of Object.keys(variants).sort()) {
      const v = variants[key];
      const hasSmall = v.files.some((f) => f.format !== 'wav');
      for (const f of v.files) (hasSmall && f.format === 'wav' ? masters : files).push(m.dir + f.name);
    }
    for (const f of all) if (!files.includes(f) && !masters.includes(f)) older.push(f);
    if (files.length) sounds[m.id] = files.sort();
  }
  return { sounds, masters, older };
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

// For each planned art file: the highest -vNN.png in its folder. Older versions are known but not used.
function scanArt(assetsDir, S) {
  const files = {}, all = [], older = [];
  const listing = {};
  for (const m of S.ASSET_MANIFEST) {
    const dir = path.posix.dirname(m.path);
    if (!(dir in listing)) { const d = path.join(assetsDir, dir); listing[dir] = fs.existsSync(d) ? fs.readdirSync(d).sort() : []; }
    let best = null, bestV = -1;
    for (const name of listing[dir]) {
      const v = S.artFileVersion(m.path, name);
      if (v == null) continue;
      all.push(dir + '/' + name);
      if (v > bestV) { bestV = v; best = dir + '/' + name; }
    }
    if (best) files[m.path] = best;
  }
  const used = new Set(Object.values(files));
  for (const f of all) if (!used.has(f)) older.push(f);
  return { files, known: new Set(all), older };
}

export function scan(root, outFile) {
  const assetsDir = path.join(root, 'assets');
  const S = loadLists();
  const manifest = S.ASSET_MANIFEST;
  const { files, known, older } = scanArt(assetsDir, S);
  const found = Object.values(files);
  const images = walk(assetsDir)
    .map((p) => path.relative(assetsDir, p).split(path.sep).join('/'))
    .filter((p) => /\.(png|gif|webp)$/i.test(p) && !known.has(p));
  // Check each file the game will load. A problem here is only a warning: the file is still listed.
  const warnings = [];
  for (const m of manifest) {
    const f = files[m.path];
    if (!f) continue;
    let list;
    try { list = checkPng(fs.readFileSync(path.join(assetsDir, f)), m.fw * m.frames, m.fh); } catch (e) { list = ['could not check this file (' + e.message + ')']; }
    for (const w of list) warnings.push(f + ': ' + w);
  }
  const { sounds, masters, older: olderSounds } = scanSounds(assetsDir, S);
  const knownSound = new Set([].concat(...Object.values(sounds), masters, olderSounds)); // older versions are ignored quietly
  const unusedSounds = walk(path.join(assetsDir, 'audio'))
    .map((p) => path.relative(assetsDir, p).split(path.sep).join('/'))
    .filter((p) => /\.(ogg|mp3|wav|m4a|aac|flac|opus)$/i.test(p) && !knownSound.has(p));
  const body = '// GENERATED by `node tools/scan-assets.mjs` — do not edit by hand.\n' +
    "// Lists which planned art and sound files currently exist in the library's assets/ folder.\n" +
    '// Art: planned name -> the newest version found. Sound: id -> files.\n' +
    '(function (S) {\n  S.PRESENT_ASSET_FILES = ' + JSON.stringify(files, null, 2).replace(/\n/g, '\n  ') + ';\n' +
    '  S.PRESENT_SOUND_FILES = ' + JSON.stringify(sounds, null, 2).replace(/\n/g, '\n  ') + ';\n' +
    '})(globalThis.SAMMY = globalThis.SAMMY || {});\n';
  fs.writeFileSync(outFile, body);
  return { expected: manifest.length, files, found, older, unused: images, warnings,
    soundsExpected: S.SOUND_MANIFEST.length, sounds, masters, unusedSounds };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
  const root = path.resolve(arg('--root', path.join(gameDir, '..')));
  const out = path.resolve(arg('--out', path.join(gameDir, 'src', 'asset-files.js')));
  const r = scan(root, out);
  console.log(`Art files found: ${r.found.length} of ${r.expected} planned.`);
  for (const f of r.found) console.log('  + ' + f);
  if (r.older.length) console.log(`(${r.older.length} older version(s) skipped because a newer one exists.)`);
  if (r.warnings.length) {
    console.log('Art warnings (see game/README.md, "Adding art"):');
    for (const w of r.warnings) console.log('  ! ' + w);
  }
  if (r.unused.length) {
    console.log('Images in assets/ that the game does not use yet (check names against templates/examples):');
    for (const f of r.unused) console.log('  ? ' + f);
  }
  const ids = Object.keys(r.sounds);
  console.log(`Sounds found: ${ids.length} of ${r.soundsExpected} planned.`);
  for (const id of ids) console.log('  + ' + r.sounds[id].join(', '));
  if (r.masters.length) console.log(`(${r.masters.length} .wav master file(s) skipped because an .ogg or .mp3 of the same sound exists.)`);
  if (r.unusedSounds.length) {
    console.log('Sound files in assets/audio/ that the game does not use (expected <folder name>-v01.ogg, e.g. sfx-jump/sfx-jump-v01.ogg):');
    for (const f of r.unusedSounds) console.log('  ? ' + f);
  }
  console.log('Wrote ' + path.relative(process.cwd(), out));
}
